#!/usr/bin/env bash
# Helpers shared by the step scripts of Visual Update Guard. Sourced, never run on their own.

export COREPACK_ENABLE_DOWNLOAD_PROMPT=0

log()  { printf '[visual-update-guard] %s\n' "$*"; }
warn() { printf '::warning title=Visual Update Guard::%s\n' "$*"; }

# version_ge "Version 1.50.1" 1.28 is true when the first version is at least the second one
version_ge() {
  local v
  v=$(printf '%s' "$1" | grep -oE '[0-9]+(\.[0-9]+)+' | head -n1)
  [ -n "$v" ] || return 1
  [ "$(printf '%s\n%s\n' "$2" "$v" | sort -V | head -n1)" = "$2" ]
}

# Package manager of the project in $1, read from the nearest lockfile up to $2 (the repository root)
detect_pm() {
  local dir="$1" stop="$2"
  while :; do
    if [ -f "$dir/pnpm-lock.yaml" ]; then echo pnpm; return; fi
    if [ -f "$dir/yarn.lock" ]; then echo yarn; return; fi
    if [ -f "$dir/package-lock.json" ] || [ -f "$dir/npm-shrinkwrap.json" ]; then echo npm; return; fi
    if [ "$dir" = "$stop" ] || [ "$dir" = "/" ]; then break; fi
    dir=$(dirname "$dir")
  done
  echo npm
}

# Makes the package manager available: corepack first (it honours "packageManager" in package.json),
# then a global npm install as a last resort
ensure_pm() {
  local pm="$1"
  [ "$pm" = npm ] && return 0
  command -v "$pm" >/dev/null 2>&1 && return 0
  if command -v corepack >/dev/null 2>&1; then corepack enable >/dev/null 2>&1 || true; fi
  command -v "$pm" >/dev/null 2>&1 || npm install --global "$pm" --no-fund --no-audit --loglevel=error
}

yarn_major() { (cd "$1" && yarn --version 2>/dev/null) | cut -d. -f1; }

# Install command used when install-command is empty. $1 package manager, $2 project root
default_install() {
  case "$1" in
    pnpm) echo "pnpm install --frozen-lockfile" ;;
    yarn)
      if [ "$(yarn_major "$2")" -ge 2 ] 2>/dev/null; then echo "yarn install --immutable"
      else echo "yarn install --frozen-lockfile"; fi ;;
    *)
      if [ -f "$2/package-lock.json" ] || [ -f "$2/npm-shrinkwrap.json" ]; then echo "npm ci"
      else echo "npm install"; fi ;;
  esac
}

# How to call the project's own Playwright. "npx --no" never downloads a different copy
playwright_cmd() {
  case "$1" in
    pnpm) echo "pnpm exec playwright" ;;
    yarn) echo "yarn playwright" ;;
    *) echo "npx --no -- playwright" ;;
  esac
}

# "module" or "" for the nearest package.json above $1
package_type() {
  local dir="$1"
  while :; do
    if [ -f "$dir/package.json" ]; then
      node -p 'require(process.argv[1]).type || ""' "$dir/package.json" 2>/dev/null || true
      return
    fi
    if [ "$dir" = "/" ]; then return; fi
    dir=$(dirname "$dir")
  done
}

# Writes a config next to the user's one ($1, absolute path) that reuses it unchanged except for two
# things: the snapshots live in $VUG_SNAPSHOT_TEMPLATE (a folder outside git) and updateSnapshots is
# $VUG_UPDATE_SNAPSHOTS. Living next to the original keeps every relative path (testDir, webServer,
# globalSetup) exactly as the user wrote it. Prints the path of the new file.
write_wrapper() {
  local config="$1" dir file ext wrapper import_path syntax
  dir=$(dirname "$config")
  file=$(basename "$config")
  ext="${file##*.}"
  case "$ext" in
    ts|tsx) syntax=esm; import_path="./${file%.*}" ;;
    mts|cts|mjs) syntax=esm; import_path="./$file" ;;
    cjs) syntax=cjs; import_path="./$file" ;;
    js) import_path="./$file"; if [ "$(package_type "$dir")" = module ]; then syntax=esm; else syntax=cjs; fi ;;
    *) return 1 ;;
  esac
  wrapper="$dir/.visual-update-guard.config.$ext"

  {
    echo "// Generated by Visual Update Guard and deleted when the action ends."
    if [ "$syntax" = esm ]; then
      echo "import userConfig from '$import_path';"
    else
      echo "const loaded = require('$import_path');"
      echo "const userConfig = (loaded && loaded.default) || loaded;"
    fi
    cat <<'JS'
const template = process.env.VUG_SNAPSHOT_TEMPLATE;
const relocate = (c) => {
  if (!c || typeof c !== 'object') return c;
  const out = { ...c, snapshotPathTemplate: template };
  const shot = c.expect && c.expect.toHaveScreenshot;
  if (shot && shot.pathTemplate) out.expect = { ...c.expect, toHaveScreenshot: { ...shot, pathTemplate: template } };
  return out;
};
const config = relocate(userConfig);
if (Array.isArray(userConfig.projects)) config.projects = userConfig.projects.map(relocate);
config.updateSnapshots = process.env.VUG_UPDATE_SNAPSHOTS;
JS
    if [ "$syntax" = esm ]; then echo "export default config;"; else echo "module.exports = config;"; fi
  } > "$wrapper"

  printf '%s\n' "$wrapper" >> "$VUG_TMP/wrappers.txt"
  printf '%s\n' "$wrapper"
}

# Runs one side (install, setup, build, browsers, tests) in a single bash process, so that variables
# exported by setup-command reach the build and the tests.
#   $1 side (before|after)   $2 project root   $3 repository root   $4 updateSnapshots mode   $5 reporters
# Leaves in $VUG_TMP: <side>.phase (last phase started), <side>.pw-version and <side>.test-rc.
# Returns non-zero when a phase before the tests failed.
run_side() {
  local side="$1" root="$2" repo="$3" mode="$4" reporters="$5"
  local pm install pw wrapper deps script="$VUG_TMP/$side.sh" phase_file="$VUG_TMP/$side.phase"

  pm=$(detect_pm "$root" "$repo")
  install="${INPUT_INSTALL_COMMAND:-}"
  [ -n "$install" ] || install=$(default_install "$pm" "$root")
  pw=$(playwright_cmd "$pm")
  deps=""
  [ "${INPUT_INSTALL_DEPS:-true}" = true ] && deps="--with-deps"

  echo config > "$phase_file"
  wrapper=$(write_wrapper "$root/$INPUT_PLAYWRIGHT_CONFIG") || {
    log "Unsupported config file: $INPUT_PLAYWRIGHT_CONFIG (expected .ts, .js, .mjs, .cjs, .mts or .cts)"
    return 1
  }

  {
    echo 'set -eo pipefail'
    echo 'export COREPACK_ENABLE_DOWNLOAD_PROMPT=0'
    declare -f ensure_pm
    printf 'cd %q\n' "$root"
    printf 'export VUG_SIDE=%q VUG_ROOT=%q\n' "$side" "$root"
    printf 'echo install > %q\n' "$phase_file"
    printf 'ensure_pm %q\n' "$pm"
    printf '%s\n' "$install"
    printf 'echo setup > %q\n' "$phase_file"
    printf '%s\n' "${INPUT_SETUP_COMMAND:-}"
    printf 'echo build > %q\n' "$phase_file"
    printf '%s\n' "${INPUT_BUILD_COMMAND:-}"
    printf 'echo browsers > %q\n' "$phase_file"
    printf '%s install %s %s\n' "$pw" "$deps" "${INPUT_BROWSERS:-}"
    printf '%s --version > %q\n' "$pw" "$VUG_TMP/$side.pw-version"
    printf 'echo test > %q\n' "$phase_file"
    echo 'set +e'
    printf '%s test --config %q --output %q --reporter %q %s\n' \
      "$pw" "$wrapper" "$VUG_TMP/$side-output" "$reporters" "${INPUT_PLAYWRIGHT_ARGS:-}"
    printf 'echo $? > %q\n' "$VUG_TMP/$side.test-rc"
  } > "$script"

  echo "::group::Visual Update Guard: $side ($root)"
  VUG_SNAPSHOT_TEMPLATE="$VUG_TMP/reference/{testFilePath}/{arg}{-projectName}{-snapshotSuffix}{ext}" \
    VUG_UPDATE_SNAPSHOTS="$mode" bash "$script"
  local rc=$?
  echo "::endgroup::"
  return $rc
}
